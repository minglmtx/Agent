"""Synthetic GPX capability fixture, never installed by task workers implicitly.

Native Trace#import parses points and produces its own icon/preview. These are
invented local test records, not reconstructed Go-Browse or real survey data.
"""
import json
from pathlib import Path
from .map_community_fixture import USERNAME

VERSION='synthetic-local-gps-capability-v1'
TRACES=[
 {'name':'local-fixture-park-walk.gpx','description':'Synthetic local benchmark trace: park walk. Not an actual GPS survey.',
  'visibility':'public','day':'2023-03-30','points':[(40.7810,-73.9670),(40.7815,-73.9665),(40.7820,-73.9660)]},
 {'name':'local-fixture-riverside-walk.gpx','description':'Synthetic local benchmark trace: riverside walk. Not an actual GPS survey.',
  'visibility':'identifiable','day':'2023-03-31','points':[(40.7200,-74.0130),(40.7205,-74.0125),(40.7210,-74.0120)]},
]


def gpx(row):
    points=''.join(f'<trkpt lat="{lat:.4f}" lon="{lon:.4f}"><ele>10</ele><time>{row["day"]}T10:{i:02d}:00Z</time></trkpt>'
                   for i,(lat,lon)in enumerate(row['points']))
    return '<?xml version="1.0" encoding="UTF-8"?>\n<gpx version="1.1" creator="Synthetic local benchmark" xmlns="http://www.topografix.com/GPX/1/1"><trk><name>'+row['name']+'</name><trkseg>'+points+'</trkseg></trk></gpx>\n'


def seed_source(*,stable_keys=False):
    payload=json.dumps({'username':USERNAME,'stable_keys':stable_keys,'traces':[dict(r,gpx=gpx(r))for r in TRACES]})
    return '''require "json"
require "stringio"
require "time"
require "digest"
spec = JSON.parse(<<'LOCAL_GPS_FIXTURE_JSON')
'''+payload+'''
LOCAL_GPS_FIXTURE_JSON
raise "Trace baseline is not empty" unless Trace.count.zero? && Tracepoint.count.zero?
user = User.find_by!(:display_name => spec.fetch("username"))
spec.fetch("traces").each do |row|
  trace = Trace.create!(:user => user, :name => row.fetch("name"),
    :description => row.fetch("description"), :timestamp => Time.iso8601(row.fetch("day") + "T10:00:00Z"),
    :visibility => row.fetch("visibility"), :visible => true, :inserted => false)
  trace.file.attach(:io => StringIO.new(row.fetch("gpx")), :filename => row.fetch("name"),
                    :content_type => "application/gpx+xml", :identify => false)
  trace.import
  trace.reload
  raise "Native import did not finish" unless trace.inserted && trace.size == row.fetch("points").size
  raise "Native attachments missing" unless trace.file.attached? && trace.image.attached? && trace.icon.attached?
  if spec.fetch("stable_keys")
    # Preserve native generated bytes, but remove random storage paths from
    # reproducible fixture baselines. This runs only before the write guard.
    {"file" => trace.file, "image" => trace.image, "icon" => trace.icon}.each do |kind, attachment|
      blob = attachment.blob
      key = Digest::SHA256.hexdigest("synthetic-local-community-gps-v1:" + row.fetch("name") + ":" + kind)
      raise "Fixture attachment key collision" if ActiveStorage::Blob.where(:key => key).exists?
      previous = blob.key
      bytes = blob.download
      blob.service.upload(key, StringIO.new(bytes), :checksum => blob.checksum)
      blob.update!(:key => key)
      raise "Attachment bytes changed" unless blob.download == bytes
      blob.service.delete(previous)
    end
  end
end
puts "Synthetic GPX records imported with native Trace#import"
'''


def install(site,*,stable_keys=False):
    if not site.state.is_relative_to(Path(site.temporary.name))or site.rails_command[-5]!='server':
        raise ValueError('Disposable native Rails instance required')
    path=site.state/'frontend/app/tmp/local-gps-fixture.rb';path.write_text(seed_source(stable_keys=stable_keys))
    site.run(site.rails_command[:-5]+['runner','/app/tmp/local-gps-fixture.rb'],'seed_local_gps_fixture',240)


def records(site):
    return json.loads(site.app_sql("""SELECT json_build_object(
      'traces',(SELECT json_agg(x ORDER BY x.id) FROM
        (SELECT g.id,u.display_name,g.name,g.description,g.visibility,g.visible,g.inserted,g.size,
                g.latitude,g.longitude,g.timestamp,
                (SELECT count(*) FROM gps_points p WHERE p.gpx_id=g.id) AS points
         FROM gpx_files g JOIN users u ON u.id=g.user_id)x));"""))
