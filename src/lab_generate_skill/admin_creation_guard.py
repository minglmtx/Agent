"""Validate a declared product creation without relaxing unrelated-state checks.

This pure checker consumes trusted database snapshots; it does not substitute
for the native renderer or the persisted image-byte collector.
"""
from copy import deepcopy
from decimal import Decimal, InvalidOperation


def creation_checks(before, after, material):
    if before.get('record_errors') or after.get('record_errors'):
        raise ValueError('Complete read-only state capture required')
    initial = before['records']['product']
    final = after['records']['product']
    if not isinstance(initial, list) or not isinstance(final, list):
        raise ValueError('Product inventories required')
    old_ids = {str(p['entity_id']) for p in initial}
    if len(old_ids) != len(initial):
        raise ValueError('Initial product IDs must be unique')
    if any(p['sku'] == material['sku'] for p in initial):
        raise ValueError('Creation target already exists at the declared start')
    targets = [p for p in final if p['sku'] == material['sku']]
    if len(targets) != 1:
        return {'one_new_target': False, 'unrelated_state_unchanged': after == before}
    target = targets[0]
    pid = str(target['entity_id'])
    new = pid not in old_ids and sum(str(p['entity_id']) == pid for p in final) == 1
    if not new:
        return {'one_new_target': False, 'unrelated_state_unchanged': after == before}
    try:
        price_ok = Decimal(str(target['price'])) == Decimal(material['price'])
    except (InvalidOperation, ValueError, TypeError):
        price_ok = False
    restored = deepcopy(after)
    restored['records']['product'] = [p for p in final if str(p['entity_id']) != pid]
    # Magento may create a native product-view rewrite for the newly created
    # product. Only new, automatically generated, local view rewrites qualify.
    old_rewrites = before['records']['url_rewrite']
    new_rewrites = after['records']['url_rewrite']
    old_keys = {str(r['entity_id']) for r in old_rewrites}
    allowed = []
    for row in new_rewrites:
        if str(row['entity_id']) in old_keys:
            continue
        if (row.get('entity_type') == 'product'
                and row.get('target_path') == 'catalog/product/view/id/' + pid
                and row.get('redirect_type') == 0 and row.get('is_autogenerated') == 1
                and str(row.get('store_id')) == str(material['store_id'])
                and row.get('request_path') == target.get('url_key', '') + '.html'):
            allowed.append(row)
    restored['records']['url_rewrite'] = [r for r in new_rewrites if r not in allowed]
    return dict(one_new_target=True, correct_name=target['name'] == material['name'],
                correct_price=price_ok, unrelated_state_unchanged=restored == before)
